import { describe, expect, it } from "vitest";

type 紀錄 = { 日期: string; 類型: string; 品項: string; 數量: number };

function 小值數量(大值數量: number, 換算比例: number) {
  return 大值數量 * 換算比例;
}

function 可提交每日盤點(紀錄: 紀錄[], 日期: string) {
  return !紀錄.some(紀錄 => 紀錄.類型 === "每日盤點" && 紀錄.日期 === 日期);
}

function 日期區段篩選(紀錄: 紀錄[], 開始日期: string, 結束日期: string) {
  return 紀錄.filter(紀錄 => 紀錄.日期 >= 開始日期 && 紀錄.日期 <= 結束日期);
}

describe("食包材庫存規則", () => {
  it("能將大值數量換算為小值數量", () => {
    expect(小值數量(3, 20)).toBe(60);
  });

  it("同一日期完成盤點後不得再次提交", () => {
    const 紀錄: 紀錄[] = [{ 日期: "2026-08-17", 類型: "每日盤點", 品項: "水餃皮", 數量: 10 }];
    expect(可提交每日盤點(紀錄, "2026-08-17")).toBe(false);
    expect(可提交每日盤點(紀錄, "2026-08-18")).toBe(true);
  });

  it("能依日期區段篩選作業紀錄", () => {
    const 紀錄: 紀錄[] = [
      { 日期: "2026-08-01", 類型: "進貨", 品項: "水餃皮", 數量: 1 },
      { 日期: "2026-08-10", 類型: "報廢", 品項: "高麗菜", 數量: 2 },
      { 日期: "2026-08-20", 類型: "退貨", 品項: "食用油", 數量: 1 },
    ];
    expect(日期區段篩選(紀錄, "2026-08-01", "2026-08-15")).toHaveLength(2);
  });
});
