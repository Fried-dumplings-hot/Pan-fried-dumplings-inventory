import { describe, expect, it } from "vitest";
import { 解析批次品項, 找出低庫存 } from "../shared/inventoryFeatures";

describe("品項批次匯入與低庫存規則", () => {
  it("可解析含標題的品項與初始庫存", () => {
    const result = 解析批次品項("品項名稱,進貨單價,大值單位,小值單位,換算比例,初始庫存,低庫存門檻\n高麗菜豬肉水餃,200,包,顆,100,5,2");
    expect(result.error).toBe("");
    expect(result.data[0]).toMatchObject({ 名稱: "高麗菜豬肉水餃", 庫存: 5, 低庫存門檻: 2 });
  });

  it("拒絕既有或同批重複品項", () => {
    expect(解析批次品項("保鮮膜,100,箱,包,20,1,1", ["保鮮膜"]).error).toContain("重複");
    expect(解析批次品項("保鮮膜,100,箱,包,20,1,1\n保鮮膜,100,箱,包,20,1,1").error).toContain("重複");
  });

  it("只標示門檻大於零且庫存低於或等於門檻的品項", () => {
    expect(找出低庫存([{ 庫存: 2, 低庫存門檻: 2 }, { 庫存: 5, 低庫存門檻: 2 }, { 庫存: 0, 低庫存門檻: 0 }])).toHaveLength(1);
  });

  it("驗證貨品代號格式並統一英文字母為大寫", () => {
    const result = 解析批次品項("貨品代號,品項名稱,進貨單價,大值單位,小值單位,換算比例,初始庫存,低庫存門檻\na000001,高麗菜豬肉水餃,200,包,顆,100,5,2");
    expect(result.error).toBe("");
    expect(result.data[0]).toMatchObject({ 貨品代號: "A000001", 名稱: "高麗菜豬肉水餃" });
    expect(解析批次品項("貨品代號,品項名稱,進貨單價,大值單位,小值單位,換算比例,初始庫存,低庫存門檻\nAA00001,錯誤品項,1,包,顆,1,0,0").error).toContain("格式不正確");
  });

  it("拒絕同批重複貨品代號並相容舊版七欄格式", () => {
    expect(解析批次品項("貨品代號,品項名稱,進貨單價,大值單位,小值單位,換算比例,初始庫存,低庫存門檻\nA000001,甲品,1,包,顆,1,0,0\nA000001,乙品,1,包,顆,1,0,0").error).toContain("重複");
    const legacy = 解析批次品項("品項名稱,進貨單價,大值單位,小值單位,換算比例,初始庫存,低庫存門檻\n舊品項,1,包,顆,1,0,0");
    expect(legacy.error).toBe("");
    expect(legacy.data[0].貨品代號).toBe("A000001");
  });
});
