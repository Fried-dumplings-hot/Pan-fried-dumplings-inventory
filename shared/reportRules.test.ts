import { describe, expect, it } from "vitest";
import { 建立門市庫存明細, 格式化類型摘要, 依日期彙整紀錄, 篩選報表作業類型, 計算門市庫存價值 } from "./reportRules";

describe("每日紀錄彙整", () => {
  it("將同日進貨、退貨、報廢與盤點合併並保留全部明細", () => {
    const result = 依日期彙整紀錄([
      { id: 1, 日期: "2026-08-17", 類型: "進貨", 品項: "水餃", 數量: 2, 單位: "箱", 備註: "上午" },
      { id: 2, 日期: "2026-08-17", 類型: "退貨", 品項: "水餃", 數量: 1, 單位: "包" },
      { id: 3, 日期: "2026-08-17", 類型: "報廢", 品項: "水餃", 數量: 1, 單位: "包" },
      { id: 4, 日期: "2026-08-17", 類型: "每日盤點", 品項: "水餃", 數量: 8, 單位: "包" },
      { id: 5, 日期: "2026-08-16", 類型: "進貨", 品項: "醬料", 數量: 3, 單位: "瓶" },
    ]);

    expect(result).toHaveLength(2);
    expect(result[0].日期).toBe("2026-08-17");
    expect(result[0].總筆數).toBe(4);
    expect(result[0].明細.map(record => record.id)).toEqual([1, 2, 3, 4]);
    expect(result[0].類型摘要).toEqual({ 進貨: 1, 退貨: 1, 報廢: 1, 每日盤點: 1 });
    expect(格式化類型摘要(result[0].類型摘要)).toBe("進貨 1 筆、退貨 1 筆、報廢 1 筆、每日盤點 1 筆");
  });
});


