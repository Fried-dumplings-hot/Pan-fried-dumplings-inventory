import { describe, expect, it } from "vitest";
import { 刪除共享異動, 取得共享異動, 修改共享異動, 新增共享異動, type 共享資料狀態 } from "./collaborationRules";

describe("跨角色共享異動規則", () => {
  it("一般員工新增後，管理員可從同一份共享狀態讀取", () => {
    const 起始: 共享資料狀態 = { 異動: [] };
    const 員工新增後 = 新增共享異動(起始, { id: 1001, 類型: "進貨", 品項: "測試品項", 數量: 2, 操作人: "F900001" });
    expect(取得共享異動(員工新增後, 1001)).toMatchObject({ 數量: 2, 操作人: "F900001" });
  });

  it("管理員修改後，一般員工讀取到同一筆的新數量", () => {
    const 狀態 = 新增共享異動({ 異動: [] }, { id: 1002, 類型: "進貨", 品項: "測試品項", 數量: 2 });
    const 管理員修改後 = 修改共享異動(狀態, { id: 1002, 類型: "進貨", 品項: "測試品項", 數量: 3, 操作人: "F999001" });
    expect(取得共享異動(管理員修改後, 1002)).toMatchObject({ 數量: 3, 操作人: "F999001" });
  });

  it("管理員刪除後，其他角色不會再讀到該筆共享紀錄", () => {
    const 狀態 = 新增共享異動({ 異動: [] }, { id: 1003, 類型: "進貨", 品項: "測試品項", 數量: 1 });
    expect(取得共享異動(刪除共享異動(狀態, 1003), 1003)).toBeUndefined();
  });
});
