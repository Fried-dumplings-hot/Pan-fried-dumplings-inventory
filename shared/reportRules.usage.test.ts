import { describe, expect, it } from "vitest";
import { 建立食包材用量報表 } from "./reportRules";

describe("食包材用量報表", () => {
  it("依先進先出拆分不同單價並計算使用量與價值", () => {
    const rows = 建立食包材用量報表(
      [
        { id: 1, 類型: "進貨", 日期: "2026-08-01", 品項: "高麗菜水餃", 數量: 10, 單位: "包", 單價: 100, 門市編號: 1 },
        { id: 2, 類型: "進貨", 日期: "2026-08-05", 品項: "高麗菜水餃", 數量: 8, 單位: "包", 單價: 120, 門市編號: 1 },
        { id: 3, 類型: "每日盤點", 日期: "2026-08-10", 品項: "高麗菜水餃", 數量: 12, 單位: "包", 門市編號: 1 },
      ],
      [{ 名稱: "高麗菜水餃", 貨品代號: "A010001", 單價: 120, 大值單位: "包" }],
      [1],
      "2026-08-01",
      "2026-08-10",
    );
    expect(rows).toHaveLength(2);
    expect(rows[0]).toMatchObject({ 單價: 100, 庫存數量盤點前: 10, 庫存數量盤點後: 10, 使用量: 0, 成本: 0, 庫存價值: 1000 });
    expect(rows[1]).toMatchObject({ 單價: 120, 庫存數量盤點前: 8, 庫存數量盤點後: 2, 使用量: 6, 成本: 720, 庫存價值: 240 });
  });

  it("沒有指定區間內盤點時不產生用量列", () => {
    const rows = 建立食包材用量報表(
      [{ id: 1, 類型: "進貨", 日期: "2026-08-01", 品項: "測試", 數量: 2, 單位: "箱", 單價: 50, 門市編號: 1 }],
      [{ 名稱: "測試", 貨品代號: "Z999999", 單價: 50, 大值單位: "箱" }],
      [1],
      "2026-08-01",
      "2026-08-10",
    );
    expect(rows).toEqual([]);
  });
});
